var activeIcons = Object.assign({}, _iconsFallback);

// Load built-in icons from Go embed, replacing static fallback.
// Called once at startup.
async function _initIcons() {
	try {
		var data = await window.go.main.App.GetBuiltinIcons();
		if (data && Object.keys(data).length > 0) {
			activeIcons = Object.assign({}, data);
			return;
		}
	} catch(e) {}
	activeIcons = Object.assign({}, _iconsFallback);
}

// Merge external icon overrides into activeIcons, preserving built-in fallback.
function applyIconTheme(ext) {
	var base = Object.assign({}, _iconsFallback);
	// Re-apply Go-loaded icons if available
	if (activeIcons && Object.keys(activeIcons).length > 0) {
		base = Object.assign({}, activeIcons);
	}
	if (!ext || !ext.icons) { activeIcons = base; return false; }
	activeIcons = Object.assign({}, base, ext.icons);
	return true;
}

function icon(key, w, h, attrs) {
	var svg = activeIcons[key];
	if (!svg) return '';
	w = w || 16;
	h = h || 16;
	var result = svg.replace('<svg', '<svg width="' + w + '" height="' + h + '"');
	if (attrs) {
		result = result.replace('<svg', '<svg ' + attrs);
	}
	return result;
}

// Auto-populate elements with [data-icon] attribute on DOM ready.
function _populateIcons() {
	document.querySelectorAll('[data-icon]').forEach(function(el) {
		var key = el.getAttribute('data-icon');
		var w = el.getAttribute('data-icon-w') || 16;
		var h = el.getAttribute('data-icon-h') || 16;
		var attrs = el.getAttribute('data-icon-attrs') || '';
		el.innerHTML = icon(key, parseInt(w), parseInt(h), attrs);
	});
}
document.addEventListener('DOMContentLoaded', function() {
	_initIcons().then(function() { _populateIcons(); });
});
