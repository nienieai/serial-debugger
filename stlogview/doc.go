// Package stlogview 是「虚窗 + 泳道滚动条」的文档侧引擎。
//
// 它替代原来那套「一次挂 150~400 行 DOM、滚到边再换一批」的显示方式：
// 文档在 Go 里只留一份 arena（原始字节）与定长帧表，按像素窗口把**可见的
// 那几十行**吐给前端；前端不再量 DOM、不再自己算折行，只做 translate3d。
//
// 三个对外入口：
//
//   - Window(contentY, viewportH, overscanPx)：按内容纵坐标取窗口。行高（一帧占
//     几行、折几行）在这里算，见 index.go 的 seg/segIdx 与 store.go 的前缀和。
//   - Ruler(nb)：滚动条要的桶。第 0 道是「来源/发送方」——.stlog 里 tx 记录带
//     origin，这是唯一真实的语义数据；「落盘」道报文件完整性（缺头/断链/末帧
//     未闭合）。桶按帧号均分，前端只画矩形。
//   - CopySelection(req)：选区（帧号 + 视觉行 + 格）换算成字节区间，按三种格式
//     输出并写进剪贴板。换算规则与渲染共用 width.go 的 unitAt，不会各算各的。
//
// 还没有的两件事（都不塞假数据）：
//
//   - 「读取」道：格式里没有「谁读过」这一维，origin 说的是发送方。等工程文件
//     补上读取记录再加，见 TODO.md「会话『读取』记录」。
//   - Modbus 校验道：先放放 —— 后面要做的是可自定义规则文件的校验引擎，不是
//     现在这版硬编码的 Modbus 检查。
//
// 实时会话（串口监视器 / 转发监视器）的文档在阶段 2 接进来：同样是 arena +
// 帧表，只是 Append 增量追加、按字节上限裁剪最早的一段。文件这一侧是只读的：
// Open 之后后台扫描，扫完 phase 变 ready。
