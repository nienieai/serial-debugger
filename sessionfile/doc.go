// Package sessionfile 实现 .stlog 会话文件的 v1.4 磁盘格式。
//
// 一个 .stlog 文件既是实时录制，也是崩溃恢复源：固定 16 KB 头部（双槽设置
// 快照 + 双影子页）之后是 4096 B 定长页，每页由页头（20 B）、统计块（44 B）、
// 记录区和整页 CRC32 组成。设计规范见 0.8.3-dev/会话文件方案-v1.4.md，
// 边界情形见同目录的《边界情形-v1.4》图。
//
// 核心不变量（改动前请先读设计文档对应章节）：
//
//   - 页内除页尾 CRC 外的任何字节都只能以整页 4096 B 写出（§2.6）；
//     没有"只改页头"或"只改统计块"的写路径。
//   - 记录永不跨页；帧可以跨页，用 dir 的 bit7 标记"帧未完"（§2.8）。
//   - 只有重写已有页时才写影子，新页首次写不写——顺序写入因此不产生额外
//     4 KB，写放大回到 1× 附近（§2.10、§2.11）。
//   - 恢复只前滚：绝不用 committedLen 更小的页覆盖更大的页（§2.10）。
//   - 续片链不能跨过缺失的页。页尾说"帧未完"而下页 firstRecOff 说"帧首
//     在此"时，两者矛盾，必须切断链而不是把两个帧粘起来（§2.9）。
//   - 统计块没有独立 CRC，读取侧不校验其自洽性，只信任整页 CRC（§2.7）。
//
// 本包只负责格式与单文件读写，不含文件锁、IPC、导出、并发写与 v1.3.1 兼容
// 模式；那些属于集成层。
